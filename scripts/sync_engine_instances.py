"""Generate optional HAOS instances from the canonical engine, without secrets."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "live_studio"
TARGET = ROOT / "live_studio_2"


def expected_files():
    config = (SOURCE / "config.yaml").read_text()
    config = config.replace("name: Live Studio Engine\n", "name: Live Studio Engine 2\n", 1)
    config = config.replace("slug: live_studio\n", "slug: live_studio_2\n", 1)
    config = config.replace("/tree/main/live_studio\n", "/tree/main/live_studio_2\n", 1)
    dockerfile = (SOURCE / "Dockerfile").read_text().replace(
        'CMD ["python3", "-m", "studio.server"]',
        'ENV STUDIO_MEDIA=/media/live_studio_2\nCMD ["python3", "-m", "studio.server"]',
    )
    files = {
        "config.yaml": config.encode(),
        "Dockerfile": dockerfile.encode(),
        ".dockerignore": (SOURCE / ".dockerignore").read_bytes(),
        "README.md": (
            "# Live Studio Engine 2\n\n"
            "Optional independent second instance of [Live Studio Engine](../live_studio/).\n"
            "Own API token, destination, settings, playlist position and output.\n"
            "Local previews: `/media/live_studio_2/preview.mp4`.\n\n"
            "See the [installation guide](../live_studio/DOCS.md#independent-second-output).\n"
            "Generated by `scripts/sync_engine_instances.py`; edit canonical sources instead.\n"
        ).encode(),
    }
    files.update({"studio/" + p.name: p.read_bytes() for p in SOURCE.glob("studio/*.py")})
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files = expected_files()
    if args.check:
        actual = {str(p.relative_to(TARGET)): p.read_bytes() for p in TARGET.rglob("*") if p.is_file()}
        if actual != files:
            raise SystemExit("Generated instance differs; run scripts/sync_engine_instances.py")
        print("Independent engine instance matches canonical sources")
        return
    TARGET.mkdir(exist_ok=True)
    for name, content in files.items():
        path = TARGET / name
        path.parent.mkdir(exist_ok=True, parents=True)
        path.write_bytes(content)
    print("Generated independent HAOS engine instance")


if __name__ == "__main__":
    main()
